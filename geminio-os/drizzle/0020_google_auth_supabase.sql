-- Geminio OS staged Google identity store (Supabase PostgreSQL)
-- Run in Supabase SQL Editor before enabling Google sign-in.
CREATE TABLE IF NOT EXISTS public.geminio_auth_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  open_id VARCHAR(255) NOT NULL UNIQUE,
  email VARCHAR(320) NOT NULL,
  name TEXT,
  login_method VARCHAR(64) NOT NULL DEFAULT 'google',
  role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_signed_in TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS geminio_auth_users_email_idx ON public.geminio_auth_users (lower(email));
ALTER TABLE public.geminio_auth_users ENABLE ROW LEVEL SECURITY;
-- Access is performed only by the backend with SUPABASE_SERVICE_ROLE_KEY.
